    /**
     * @return array{what:string,why:string,fix:string}
     */
    public static function forCode(string $code, array $meta = []): array
    {
        $map = self::map();
        if (isset($map[$code])) {
            return self::normalize($map[$code], $meta);
        }

        return self::normalize([], $meta);
    }

