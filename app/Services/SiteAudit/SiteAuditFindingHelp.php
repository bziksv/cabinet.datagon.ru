    {
        $desc = trim((string) ($meta['description'] ?? ''));
        $fix = $row['fix'] ?? $row['how'] ?? null;

        return [
            'what' => (string) ($row['what'] ?? ($desc !== '' ? $desc : 'Проверка технического аудита по этому отчёту.')),
            'why' => (string) ($row['why'] ?? 'Может влиять на индексацию, сниппеты или удобство обхода сайта.'),
            'fix' => (string) ($fix ?? 'Разберите URL из списка, устраните причину и перезапустите проверку.'),
        ];
    }

